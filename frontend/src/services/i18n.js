// Persistent Language Helper (saved in localStorage)
const STORAGE_KEY = "coop_os_lang";

export const getStoredLanguage = () => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && (saved === "en" || saved === "ta" || saved === "hi")) {
      return saved;
    }
  } catch (e) {
    // Ignore localStorage read error
  }
  return "en";
};

export const setStoredLanguage = (lang) => {
  try {
    if (lang === "en" || lang === "ta" || lang === "hi") {
      localStorage.setItem(STORAGE_KEY, lang);
    }
  } catch (e) {
    // Ignore localStorage write error
  }
};

export const getTranslation = (lang, key) => {
  const currentLang = lang || getStoredLanguage();
  const dictionary = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dictionary[key] || TRANSLATIONS.en[key] || key;
};
